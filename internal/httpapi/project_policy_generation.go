// generatedExecutionPolicy uses configured Qlty and declared project scripts, never placeholder checks.
func generatedExecutionPolicy(ctx context.Context, path string) (string, error) {
	checks := []model.Check{{Name: "qlty", Command: []string{"qlty", "check", "--no-fix", "--no-upgrade-check"}}}
	scriptChecks, err := generatedScriptChecks(ctx, path)
	if err != nil {
		return "", err
	}
	checks = append(checks, scriptChecks...)
	goChecks, err := generatedGoChecks(ctx, path)
	if err != nil {
		return "", err
	}
	checks = append(checks, goChecks...)
	allowed, err := generatedAllowedPaths(ctx, path)
	if err != nil {
		return "", err
	}
	commands := make([][]string, 0, len(checks))
	for _, check := range checks {
		commands = append(commands, check.Command)
	}
	rules := []model.RiskRule{{Level: "high", Paths: []string{"**"}}, {Level: "critical", Paths: []string{"package.json", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb", "go.mod", "go.sum", "prisma/**", ".github/**"}, CodeTypes: []string{".sql"}}}
	p := model.Policy{Checks: checks, AllowedPaths: allowed, Commands: commands, RiskRules: rules}
	if err = policy.Validate(p); err != nil {
		return "", err
	}
	value := struct {
		Checks       []model.Check    `yaml:"checks"`
		AllowedPaths []string         `yaml:"allowed_paths"`
		Commands     [][]string       `yaml:"commands"`
		RiskRules    []model.RiskRule `yaml:"risk_rules"`
	}{checks, allowed, commands, rules}
	encoded, err := yaml.Marshal(value)
	return "# Generated by Whirlwind from repository checks. Customize and commit as needed.\n" + string(encoded), err
}

type generatedManifest struct {
	PackageManager string            `json:"packageManager"`
	Scripts        map[string]string `json:"scripts"`
}

func committedProjectManifest(ctx context.Context, path string) ([]byte, error) {
	_, err := os.ReadFile(filepath.Join(path, "package.json"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	committed, err := github.Run(ctx, path, "git", "show", "HEAD:package.json")
	if err != nil {
		return nil, errors.New("commit package.json before execution setup; uncommitted manifest preserved")
	}
	return []byte(committed), nil
}

func generatedScriptChecks(ctx context.Context, path string) ([]model.Check, error) {
	data, err := committedProjectManifest(ctx, path)
	if err != nil || data == nil {
		return nil, err
	}
	var manifest generatedManifest
	if err = json.Unmarshal(data, &manifest); err != nil {
		return nil, fmt.Errorf("read project scripts: %w", err)
	}
	manager, err := generatedPackageManager(path, manifest.PackageManager)
	if err != nil {
		return nil, err
	}
	checks := []model.Check{}
	for _, name := range []string{"typecheck", "lint", "test", "build"} {
		if strings.TrimSpace(manifest.Scripts[name]) != "" {
			checks = append(checks, model.Check{Name: name, Command: []string{manager, "run", name}})
		}
	}
	return checks, nil
}

func generatedPackageManager(path, declared string) (string, error) {
	manager := "npm"
	if declared != "" {
		manager = strings.Split(declared, "@")[0]
	} else {
		for _, lock := range []struct{ name, manager string }{{"pnpm-lock.yaml", "pnpm"}, {"yarn.lock", "yarn"}, {"bun.lock", "bun"}, {"bun.lockb", "bun"}} {
			if _, err := os.Stat(filepath.Join(path, lock.name)); err == nil {
				manager = lock.manager
				break
			}
		}
	}
	switch manager {
	case "npm", "pnpm", "yarn", "bun":
	default:
		return "", fmt.Errorf("unsupported package manager %q; configure project checks explicitly", manager)
	}
	return manager, nil
}

func generatedGoChecks(ctx context.Context, path string) ([]model.Check, error) {
	checks := []model.Check{}
	if _, err := os.Stat(filepath.Join(path, "go.mod")); err == nil {
		if _, e := github.Run(ctx, path, "git", "cat-file", "-e", "HEAD:go.mod"); e != nil {
			return nil, errors.New("commit go.mod before execution setup; uncommitted module preserved")
		}
		for _, name := range []string{"test", "vet", "build"} {
			checks = append(checks, model.Check{Name: "go-" + name, Command: []string{"go", name, "./..."}})
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	return checks, nil
}

func generatedAllowedPaths(ctx context.Context, path string) ([]string, error) {
	allowed := []string{}
	for _, name := range []string{"src", "app", "pages", "components", "lib", "tests", "test", "e2e", "docs", "public", "cmd", "internal", "pkg", "scripts", "prisma"} {
		if info, e := os.Stat(filepath.Join(path, name)); e == nil && info.IsDir() {
			allowed = append(allowed, name+"/**")
		}
	}
	files, err := github.Run(ctx, path, "git", "ls-files", "-z")
	if err != nil {
		return nil, err
	}
	for _, name := range strings.Split(files, "\x00") {
		if allowedGeneratedRootFile(name) {
			allowed = append(allowed, name)
		}
	}
	if len(allowed) == 0 {
		allowed = []string{"src/**", "tests/**", "docs/**"}
	}
	sort.Strings(allowed)
	return allowed, nil
}

func allowedGeneratedRootFile(name string) bool {
	if name == "" || strings.Contains(name, "/") || strings.HasPrefix(name, ".") {
		return false
	}
	if name == "AGENTS.md" || name == "AGENTS.override.md" {
		return false
	}
	return !strings.HasSuffix(name, ".pem") && !strings.HasSuffix(name, ".key")
}
